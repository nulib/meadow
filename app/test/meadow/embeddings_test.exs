defmodule Meadow.EmbeddingsTest do
  use Meadow.DataCase

  alias Meadow.Data.Schemas.{FileSetEmbedding, WorkEmbedding}
  alias Meadow.Data.Works
  alias Meadow.Embeddings
  alias Meadow.Embeddings.Model.Stub
  alias Meadow.Embeddings.Prompt

  setup do
    start_supervised!(Stub)
    {:ok, work: work_fixture(%{descriptive_metadata: %{title: "Jazz Festival Poster"}})}
  end

  describe "embed_query/1" do
    test "embeds the text with the query prompt" do
      assert {:ok, vector} = Embeddings.embed_query("jazz posters")
      assert vector == Stub.vector(Prompt.query("jazz posters"))
      assert Stub.prompts() == ["task: search result | query: jazz posters"]
    end
  end

  describe "embed/1" do
    test "does not call the model for an empty list" do
      assert Embeddings.embed([]) == {:ok, []}
      assert Stub.prompts() == []
    end

    test "returns the model's error" do
      Stub.fail_with(:model_unavailable)
      assert Embeddings.embed(["prompt"]) == {:error, :model_unavailable}
    end
  end

  describe "embed_image/1" do
    test "embeds an image with the configured model" do
      assert Embeddings.embed_image("image bytes") == {:ok, Stub.vector("image bytes")}
    end

    test "returns the model's error" do
      Stub.fail_with(:model_unavailable)
      assert Embeddings.embed_image("image bytes") == {:error, :model_unavailable}
    end
  end

  describe "embed_file_set/2" do
    setup do
      {:ok, file_set: file_set_fixture()}
    end

    test "stores the image embedding for the file set", %{file_set: file_set} do
      assert {:ok, %FileSetEmbedding{}} = Embeddings.embed_file_set(file_set, "image bytes")

      embedding = Embeddings.get_file_set_embedding(file_set.id)
      assert embedding.model == "embeddinggemma-2"
      assert embedding.soft_tokens == 280
      assert FileSetEmbedding.to_list(embedding) == Stub.vector("image bytes")
      assert Embeddings.current_model?(embedding)
    end

    test "replaces an earlier embedding", %{file_set: file_set} do
      assert {:ok, _} = Embeddings.embed_file_set(file_set, "first")
      assert {:ok, _} = Embeddings.embed_file_set(file_set, "second")

      assert Repo.aggregate(FileSetEmbedding, :count) == 1

      assert file_set.id |> Embeddings.get_file_set_embedding() |> FileSetEmbedding.to_list() ==
               Stub.vector("second")
    end

    test "stores nothing when the model fails", %{file_set: file_set} do
      Stub.fail_with(:model_unavailable)
      assert Embeddings.embed_file_set(file_set, "image bytes") == {:error, :model_unavailable}
      refute Embeddings.get_file_set_embedding(file_set.id)
    end

    test "is removed along with its file set", %{file_set: file_set} do
      assert {:ok, _} = Embeddings.embed_file_set(file_set, "image bytes")
      Repo.delete!(file_set)
      refute Embeddings.get_file_set_embedding(file_set.id)
    end
  end

  describe "refresh_works/1" do
    test "stores an embedding for a work that has none", %{work: work} do
      assert {:ok, %{updated: [work_id], unchanged: []}} = Embeddings.refresh_works([work.id])
      assert work_id == work.id

      assert [prompt] = Stub.prompts()
      assert prompt =~ "title: Jazz Festival Poster | text: title: Jazz Festival Poster"

      assert %WorkEmbedding{} = embedding = Embeddings.get_work_embedding(work.id)
      assert embedding.model == "embeddinggemma-2"
      assert embedding.text_hash == Embeddings.Text.hash(prompt)
      assert embedding.text_length > 0
      assert WorkEmbedding.to_list(embedding) == Stub.vector(prompt)
    end

    test "does not embed a work whose text is unchanged", %{work: work} do
      assert {:ok, %{updated: [_]}} = Embeddings.refresh_works([work.id])
      Works.update_work!(Works.get_work!(work.id), %{published: true})

      assert {:ok, %{updated: [], unchanged: [_]}} = Embeddings.refresh_works([work.id])
      assert length(Stub.prompts()) == 1
    end

    test "replaces the embedding when the text changes", %{work: work} do
      assert {:ok, _} = Embeddings.refresh_works([work.id])
      before = Embeddings.get_work_embedding(work.id)

      Works.get_work!(work.id)
      |> Works.update_work!(%{descriptive_metadata: %{title: "Blues Festival Poster"}})

      assert {:ok, %{updated: [_]}} = Embeddings.refresh_works([work.id])
      updated = Embeddings.get_work_embedding(work.id)
      assert updated.text_hash != before.text_hash
      assert WorkEmbedding.to_list(updated) == Stub.vector(List.last(Stub.prompts()))
      assert Repo.aggregate(WorkEmbedding, :count) == 1
    end

    test "replaces an embedding generated by another model", %{work: work} do
      assert {:ok, _} = Embeddings.refresh_works([work.id])

      from(e in WorkEmbedding, where: e.work_id == ^work.id)
      |> Repo.update_all(set: [model: "cohere.embed-multilingual-v3"])

      assert {:ok, %{updated: [_]}} = Embeddings.refresh_works([work.id])
      assert Embeddings.get_work_embedding(work.id).model == "embeddinggemma-2"
    end

    test "embeds several works in a single model call", %{work: work} do
      other = work_fixture(%{descriptive_metadata: %{title: "Another"}})

      assert {:ok, %{updated: updated}} = Embeddings.refresh_works([work.id, other.id])
      assert Enum.sort(updated) == Enum.sort([work.id, other.id])
      assert length(Stub.prompts()) == 2
    end

    test "ignores works that do not exist" do
      assert Embeddings.refresh_works([Ecto.UUID.generate()]) ==
               {:ok, %{updated: [], unchanged: []}}
    end

    test "stores nothing when the model fails", %{work: work} do
      Stub.fail_with(:model_unavailable)
      assert Embeddings.refresh_works([work.id]) == {:error, :model_unavailable}
      refute Embeddings.get_work_embedding(work.id)
    end

    test "is removed along with its work", %{work: work} do
      assert {:ok, _} = Embeddings.refresh_works([work.id])
      Works.delete_work(Works.get_work!(work.id))
      refute Embeddings.get_work_embedding(work.id)
    end
  end

  describe "backfill_file_sets/1" do
    setup do
      config = Application.get_env(:meadow, Meadow.Embeddings)

      Application.put_env(
        :meadow,
        Meadow.Embeddings,
        Keyword.put(config, :req_options, plug: {Req.Test, __MODULE__}, retry: false)
      )

      on_exit(fn -> Application.put_env(:meadow, Meadow.Embeddings, config) end)

      Req.Test.stub(__MODULE__, fn conn ->
        if String.ends_with?(conn.request_path, "/info.json"),
          do: Req.Test.json(conn, %{"width" => 1024, "height" => 1024}),
          else: Plug.Conn.send_resp(conn, 200, "image for #{conn.request_path}")
      end)

      image = fn role, mime_type, derivatives ->
        file_set_fixture(%{
          role: %{id: role, scheme: "FILE_SET_ROLE"},
          core_metadata: %{
            location: "s3://ingest/file",
            original_filename: "file",
            mime_type: mime_type
          },
          derivatives: derivatives
        })
      end

      pyramid = %{"pyramid_tiff" => "s3://pyramids/image.tif"}

      {:ok,
       access: image.("A", "image/tiff", pyramid),
       auxiliary: image.("X", "image/jpeg", pyramid),
       preservation: image.("P", "image/tiff", pyramid),
       audio: image.("A", "audio/x-wav", %{}),
       no_pyramid: image.("A", "image/tiff", %{})}
    end

    test "embeds Access and Auxiliary image file sets that have an IIIF image", context do
      assert {:ok, %{embedded: 2, failed: [{failed_id, :no_image}]}} =
               Embeddings.backfill_file_sets()

      assert failed_id == context.no_pyramid.id
      assert Embeddings.get_file_set_embedding(context.access.id)
      assert Embeddings.get_file_set_embedding(context.auxiliary.id)
      refute Embeddings.get_file_set_embedding(context.preservation.id)
      refute Embeddings.get_file_set_embedding(context.audio.id)
    end

    test "only embeds file sets without a current embedding by default", context do
      assert {:ok, %{embedded: 2}} = Embeddings.backfill_file_sets(chunk_size: 1)
      assert {:ok, %{embedded: 0}} = Embeddings.backfill_file_sets()

      Repo.update_all(
        from(e in FileSetEmbedding, where: e.file_set_id == ^context.access.id),
        set: [model: "some-other-model"]
      )

      assert {:ok, %{embedded: 1}} = Embeddings.backfill_file_sets()
      assert {:ok, %{embedded: 2}} = Embeddings.backfill_file_sets(scope: :all)
    end

    test "carries on after a failure", context do
      Stub.fail_with(:model_unavailable)
      assert {:ok, %{embedded: 0, failed: failed}} = Embeddings.backfill_file_sets()
      assert {context.access.id, :model_unavailable} in failed
      assert length(failed) == 3
    end
  end

  describe "backfill/1" do
    test "embeds only works without a current embedding by default", %{work: work} do
      other = work_fixture()
      assert {:ok, _} = Embeddings.refresh_works([work.id])

      assert Embeddings.backfill(chunk_size: 1) == {:ok, 1}
      assert Embeddings.get_work_embedding(other.id)
      assert Embeddings.backfill() == {:ok, 0}
    end

    test "re-embeds works whose embedding came from another model", %{work: work} do
      assert {:ok, _} = Embeddings.refresh_works([work.id])
      Repo.update_all(WorkEmbedding, set: [model: "other"])

      assert Embeddings.backfill() == {:ok, 1}
    end

    test "checks every work with scope: :all", %{work: work} do
      assert {:ok, _} = Embeddings.refresh_works([work.id])

      Works.get_work!(work.id)
      |> Works.update_work!(%{descriptive_metadata: %{title: "Changed"}})

      assert Embeddings.backfill() == {:ok, 0}
      assert Embeddings.backfill(scope: :all) == {:ok, 1}
    end

    test "stops at the first failure" do
      Stub.fail_with(:model_unavailable)
      assert Embeddings.backfill() == {:error, :model_unavailable}
    end
  end
end
