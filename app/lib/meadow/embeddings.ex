defmodule Meadow.Embeddings do
  @moduledoc """
  Generates and stores embeddings for works (text) and file sets (images).

  Meadow embeds each work itself and keeps the vector in the
  `work_embeddings` table. The search index copies the stored vector into
  the work document, so reindexing never has to run the model again.

  Image file sets are embedded by the `EmbedImage` pipeline action and kept
  in `file_set_embeddings`. Text and image vectors share one space.
  """

  import Ecto.Query

  alias Meadow.Data.Schemas.{FileSet, FileSetEmbedding, Work, WorkEmbedding}
  alias Meadow.Embeddings.{Config, IIIFImage, Prompt, Text}
  alias Meadow.Indexing.V2.Work, as: WorkDocument
  alias Meadow.Repo

  require Logger

  # File set roles whose images are embedded: Access and Auxiliary
  @image_roles ~w(A X)

  @type refresh_result :: %{updated: [Ecto.UUID.t()], unchanged: [Ecto.UUID.t()]}

  defdelegate enabled?, to: Config

  @doc "Embed a search query. Returns `{:ok, vector}`"
  @spec embed_query(String.t()) :: {:ok, [float()]} | {:error, term()}
  def embed_query(text) when is_binary(text) do
    with {:ok, [vector]} <- embed([Prompt.query(text)]), do: {:ok, vector}
  end

  @doc "Embed complete prompts with the configured model"
  @spec embed([String.t()]) :: {:ok, [[float()]]} | {:error, term()}
  def embed([]), do: {:ok, []}

  def embed(prompts) when is_list(prompts) do
    dimensions = Config.dimensions()

    with {:ok, vectors} <- Config.model().embed(prompts) do
      if length(vectors) == length(prompts) and Enum.all?(vectors, &(length(&1) == dimensions)),
        do: {:ok, vectors},
        else: {:error, :unexpected_embedding_shape}
    end
  end

  @doc "Embed an encoded image (JPEG, PNG, TIFF, ...) with the configured model"
  @spec embed_image(binary()) :: {:ok, [float()]} | {:error, term()}
  def embed_image(image) when is_binary(image) do
    with {:ok, vector} <- Config.model().embed_image(image) do
      if length(vector) == Config.dimensions(),
        do: {:ok, vector},
        else: {:error, :unexpected_embedding_shape}
    end
  end

  @doc "Fetch the stored embedding for a file set"
  def get_file_set_embedding(file_set_id),
    do: Repo.get_by(FileSetEmbedding, file_set_id: file_set_id)

  @doc """
  Embed an image and store the vector as the file set's embedding, replacing
  any earlier one.
  """
  @spec embed_file_set(FileSet.t(), binary()) :: {:ok, FileSetEmbedding.t()} | {:error, term()}
  def embed_file_set(%FileSet{id: file_set_id}, image) when is_binary(image) do
    with {:ok, vector} <- embed_image(image) do
      %FileSetEmbedding{file_set_id: file_set_id}
      |> FileSetEmbedding.changeset(%{
        model: Config.model_name(),
        soft_tokens: Config.image_soft_tokens(),
        embedding: vector
      })
      |> Repo.insert(
        on_conflict: {:replace, [:model, :soft_tokens, :embedding, :updated_at]},
        conflict_target: :file_set_id
      )
    end
  end

  @doc "Fetch the stored embedding for a work"
  def get_work_embedding(work_id), do: Repo.get_by(WorkEmbedding, work_id: work_id)

  @doc "Build the embedding text for a work loaded with `Work.required_index_preloads/0`"
  @spec text_for(Work.t()) :: Text.t()
  def text_for(%Work{} = work), do: work |> WorkDocument.encode() |> Text.build()

  @doc "Whether a stored embedding was generated by the configured model"
  def current_model?(%WorkEmbedding{model: model}), do: model == Config.model_name()
  def current_model?(%FileSetEmbedding{model: model}), do: model == Config.model_name()
  def current_model?(_), do: false

  @doc """
  Bring the stored embeddings for the given works up to date.

  A work is embedded only when it has no stored embedding, its embedding
  text has changed, or its embedding came from a different model. Works
  that no longer exist are ignored.
  """
  @spec refresh_works([Ecto.UUID.t()]) :: {:ok, refresh_result()} | {:error, term()}
  def refresh_works(work_ids) when is_list(work_ids) do
    {stale, unchanged} =
      from(w in Work, where: w.id in ^work_ids, preload: ^Work.required_index_preloads())
      |> Repo.all()
      |> Enum.map(&{&1, text_for(&1)})
      |> Enum.split_with(fn {work, text} -> stale?(work.embedding, text) end)

    with {:ok, vectors} <- stale |> Enum.map(fn {_, text} -> text.prompt end) |> embed() do
      stale
      |> Enum.zip(vectors)
      |> Enum.each(fn {{work, text}, vector} -> store!(work, text, vector) end)

      {:ok,
       %{
         updated: Enum.map(stale, fn {work, _} -> work.id end),
         unchanged: Enum.map(unchanged, fn {work, _} -> work.id end)
       }}
    end
  end

  @doc """
  Embed works in bulk, in chunks.

  By default only works with no embedding from the configured model are
  processed. Pass `scope: :all` to check every work; works whose text has
  not changed are still skipped.

  ## Options

    * `:scope` - `:missing` (default) or `:all`
    * `:chunk_size` - number of works loaded and embedded at a time (default: 50)

  Returns the number of works embedded.
  """
  @spec backfill(keyword()) :: {:ok, non_neg_integer()} | {:error, term()}
  def backfill(opts \\ []) do
    chunk_size = Keyword.get(opts, :chunk_size, 50)

    opts
    |> Keyword.get(:scope, :missing)
    |> backfill_query()
    |> Repo.all(timeout: :infinity)
    |> Enum.chunk_every(chunk_size)
    |> Enum.reduce_while({:ok, 0}, fn work_ids, {:ok, count} ->
      case refresh_works(work_ids) do
        {:ok, %{updated: updated}} ->
          count = count + length(updated)
          Logger.info("Embedded #{count} works")
          {:cont, {:ok, count}}

        {:error, reason} ->
          {:halt, {:error, reason}}
      end
    end)
  end

  @doc """
  Embed the images of existing file sets in bulk.

  Covers what the `EmbedImage` pipeline action does for newly ingested files:
  Access and Auxiliary image file sets that have an IIIF image. By default
  only file sets with no embedding from the configured model are processed;
  pass `scope: :all` to embed every one again.

  A file set that fails (for example because its image cannot be fetched) is
  logged and skipped, so one bad file does not stop the run.

  ## Options

    * `:scope` - `:missing` (default) or `:all`
    * `:chunk_size` - number of file sets loaded at a time (default: 50)

  Returns `{:ok, %{embedded: count, failed: [{file_set_id, reason}]}}`.
  """
  @spec backfill_file_sets(keyword()) ::
          {:ok, %{embedded: non_neg_integer(), failed: [{Ecto.UUID.t(), term()}]}}
  def backfill_file_sets(opts \\ []) do
    result =
      opts
      |> Keyword.get(:scope, :missing)
      |> file_set_backfill_query()
      |> Repo.all(timeout: :infinity)
      |> Enum.chunk_every(Keyword.get(opts, :chunk_size, 50))
      |> Enum.reduce(%{embedded: 0, failed: []}, fn file_set_ids, acc ->
        from(fs in FileSet, where: fs.id in ^file_set_ids, preload: ^FileSet.metadata_preloads())
        |> Repo.all()
        |> Enum.filter(&(&1.role.id in @image_roles))
        |> Enum.reduce(acc, &backfill_file_set/2)
      end)

    {:ok, %{result | failed: Enum.reverse(result.failed)}}
  end

  defp backfill_file_set(file_set, acc) do
    with {:ok, image} <- IIIFImage.fetch(file_set),
         {:ok, _embedding} <- embed_file_set(file_set, image) do
      Logger.info("Embedded #{acc.embedded + 1} file sets")
      %{acc | embedded: acc.embedded + 1}
    else
      {:error, reason} ->
        Logger.warning("Could not embed file set #{file_set.id}: #{inspect(reason)}")
        %{acc | failed: [{file_set.id, reason} | acc.failed]}
    end
  end

  defp file_set_backfill_query(scope) do
    query =
      from(fs in FileSet,
        join: cm in assoc(fs, :core_metadata),
        where: like(cm.mime_type, "image/%"),
        select: fs.id,
        order_by: fs.id
      )

    case scope do
      :all ->
        query

      :missing ->
        model = Config.model_name()

        from(fs in query,
          left_join: e in FileSetEmbedding,
          on: e.file_set_id == fs.id and e.model == ^model,
          where: is_nil(e.file_set_id)
        )
    end
  end

  defp backfill_query(:all), do: from(w in Work, select: w.id, order_by: w.id)

  defp backfill_query(:missing) do
    model = Config.model_name()

    from(w in Work,
      left_join: e in WorkEmbedding,
      on: e.work_id == w.id and e.model == ^model,
      where: is_nil(e.work_id),
      select: w.id,
      order_by: w.id
    )
  end

  defp stale?(%WorkEmbedding{} = embedding, text),
    do: not current_model?(embedding) or embedding.text_hash != text.hash

  defp stale?(_, _), do: true

  defp store!(work, text, vector) do
    %WorkEmbedding{work_id: work.id}
    |> WorkEmbedding.changeset(%{
      model: Config.model_name(),
      text_hash: text.hash,
      text_length: text.length,
      embedding: vector
    })
    |> Repo.insert!(
      on_conflict: {:replace, [:model, :text_hash, :text_length, :embedding, :updated_at]},
      conflict_target: :work_id
    )
  end
end
